// This only caches the app's own shell files (the page itself, manifest, icons).
// It deliberately leaves every other request (jsdelivr, huggingface.co, etc.)
// completely alone — those are already cached by the page itself via the
// browser's Cache Storage API, and we don't want two caching layers fighting.

const CACHE_NAME = 'audio-notes-shell-v1';
const SHELL_FILES = [
  './',
  './index.html',
  './manifest.json',
  './icon-192.png',
  './icon-512.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(SHELL_FILES))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => n !== CACHE_NAME).map((n) => caches.delete(n)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // only handle requests for our own files; let everything else (CDN, model
  // downloads) go straight to the network untouched
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(event.request).then((cached) => cached || fetch(event.request))
  );
});
